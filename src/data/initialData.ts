export function calculateCommercialScore(scores: {
  necesidadReal: number;
  urgencia: number;
  presupuesto: number;
  claridadProyecto: number;
  poderDecision: number;
  viabilidadTecnica: number;
  potencialEconomico: number;
  probabilidadContratacion: number;
}): { puntajeTotal: number; clasificacion: CommercialPriority } {
  const puntajeTotal =
    scores.necesidadReal +
    scores.urgencia +
    scores.presupuesto +
    scores.claridadProyecto +
    scores.poderDecision +
    scores.viabilidadTecnica +
    scores.potencialEconomico +
    scores.probabilidadContratacion;

  let clasificacion: CommercialPriority = 'BAJA PRIORIDAD';
  if (puntajeTotal >= 32) {
    clasificacion = 'ALTA PRIORIDAD';
  } else if (puntajeTotal >= 24) {
    clasificacion = 'MEDIA PRIORIDAD';
  } else if (puntajeTotal >= 16) {
    clasificacion = 'SEGUIMIENTO';
  }
  return { puntajeTotal, clasificacion };
}

